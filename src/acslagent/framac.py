"""FB4C verification with an explicit partial-correctness scope.

User-requested adaptation: exclude termination/variant/decreases goals, including
termination specifications automatically generated by Frama-C 28+. All other
FB4C options, 3/8s WP limits and result classification are preserved.
"""

from __future__ import annotations

import subprocess
import time
from pathlib import Path

from acslagent.domain import FramacOutcome

# Values from the original framac.py.
WP_TIMEOUT_SECONDS = 8
PROCESS_TIMEOUT_SECONDS = 500
PROVERS = "Alt-Ergo,Z3"
EXCLUDED_GOALS = ('@terminates', '@decreases', '@variant')
PROPERTY_FILTER = '-wp-prop=' + ','.join('-' + goal for goal in EXCLUDED_GOALS)
VERIFICATION_SCOPE = 'partial_correctness'

ABORT_MARKERS = (
    "[kernel] Frama-C aborted:",
    "[kernel] Plug-in wp aborted",
    "[wp] Warning: No goal generated",
    "error: invalid preprocessing directive",
)
PROVED_MARKER = "[wp] Proved goals:"
TIMEOUT_MARKER = "[wp] [Timeout] typed_"


def classify(stdout: bytes) -> tuple[str, int, int, tuple[str, ...]]:
    """Read Frama-C stdout and return verdict, proved, total, timed-out requires.

    The verdict says how Frama-C itself ended:
      invalid - the file did not even parse or WP gave up
      pass    - proved + requires timeouts == total
      fail    - summary found with other unproved goals
      unknown - no summary and no abort marker
    strict_passed is reported separately and never changes routing.
    """
    try:
        lines = stdout.decode("utf-8").splitlines()
    except Exception:
        return "unknown", 0, 0, ()

    timed_out: list[str] = []
    for line in lines:
        if any(marker in line for marker in ABORT_MARKERS):
            return "invalid", 0, 0, tuple(timed_out)
        if TIMEOUT_MARKER in line and ("_requires (" in line or "_requires_" in line):
            timed_out.append(line.strip())
            continue
        if PROVED_MARKER not in line:
            continue
        proportion = line.split(":")[-1]
        if "/" not in proportion:
            return "unknown", 0, 0, tuple(timed_out)
        left, right = proportion.split("/", 1)
        try:
            proved, total = int(left.strip()), int(right.strip())
            verdict = "pass" if proved + len(timed_out) == total else "fail"
            return verdict, proved, total, tuple(timed_out)
        except ValueError:
            return "unknown", 0, 0, tuple(timed_out)
    return "unknown", 0, 0, tuple(timed_out)


def build_command(c_file: Path, executable: str = "frama-c", wp_timeout: int = WP_TIMEOUT_SECONDS) -> list[str]:
    return [
        executable,
        "-wp",
        PROPERTY_FILTER,
        "-wp-precond-weakening",
        "-wp-no-callee-precond",
        "-wp-prover",
        PROVERS,
        "-wp-print",
        "-wp-timeout",
        str(wp_timeout),
        str(c_file),
    ]


def run(
    c_file: Path,
    output_dir: Path,
    *,
    label: str,
    executable: str = "frama-c",
    process_timeout: int = PROCESS_TIMEOUT_SECONDS,
    wp_timeout: int = WP_TIMEOUT_SECONDS,
) -> FramacOutcome:
    """Run Frama-C once on one complete C file and keep its output.

    Frama-C output is named after `label`. The graph reuses `latest` after
    recording diagnostics in its trace; repair always reads the current log.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    command = build_command(c_file, executable, wp_timeout)
    started = time.monotonic()
    try:
        completed = subprocess.run(
            command,
            capture_output=True,
            timeout=process_timeout,
        )
    except subprocess.TimeoutExpired as expired:
        stdout = expired.stdout or b""
        stderr = expired.stderr or b""
        seconds = time.monotonic() - started
        return FramacOutcome(
            verdict="unknown",
            proved=0,
            total=0,
            command=tuple(command),
            stdout_path=_save(output_dir, label, "stdout", stdout),
            stderr_path=_save(output_dir, label, "stderr", stderr),
            seconds=round(seconds, 3),
            process_timed_out=True,
        )
    except FileNotFoundError as error:
        raise RuntimeError(
            "frama-c is not on PATH; install Frama-C with the WP plugin "
            "or pass --frama-c <path>"
        ) from error

    verdict, proved, total, timed_out = classify(completed.stdout)
    return FramacOutcome(
        verdict=verdict,
        proved=proved,
        total=total,
        timed_out_requires=timed_out,
        command=tuple(command),
        stdout_path=_save(output_dir, label, "stdout", completed.stdout),
        stderr_path=_save(output_dir, label, "stderr", completed.stderr),
        seconds=round(time.monotonic() - started, 3),
    )


def _save(directory: Path, label: str, stream: str, content: bytes) -> str:
    path = directory / f"{label}.{stream}.txt"
    if not content:
        path.unlink(missing_ok=True)
        return ""
    path.write_bytes(content)
    return str(path)
